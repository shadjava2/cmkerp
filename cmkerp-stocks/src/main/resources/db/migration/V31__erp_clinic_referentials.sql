CREATE TABLE IF NOT EXISTS erp_clinic_referentials (
  id BIGINT NOT NULL AUTO_INCREMENT,
  referential_key VARCHAR(32) NOT NULL,
  natural_key VARCHAR(64) NOT NULL,
  label VARCHAR(255) NULL,
  payload_json MEDIUMTEXT NOT NULL,
  sync_fingerprint CHAR(64) NULL,
  actif TINYINT(1) NOT NULL DEFAULT 1,
  source_system VARCHAR(32) NOT NULL DEFAULT 'ERP',
  legacy_key VARCHAR(64) NULL,
  sync_status VARCHAR(32) NOT NULL DEFAULT 'LOCAL_ONLY',
  last_synced_at DATETIME NULL,
  version INT NOT NULL DEFAULT 1,
  datecreate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  dateupdate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  usercreateid BIGINT NULL,
  userupdateid BIGINT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_erp_clinic_ref_key (referential_key, natural_key),
  KEY idx_erp_clinic_ref_actif (referential_key, actif),
  KEY idx_erp_clinic_ref_sync (referential_key, sync_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

